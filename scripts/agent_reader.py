#!/usr/bin/env python3
"""Generate the public-safe, strictly allowlisted category reader.

The static host serves checked-in files. CI compares generated bytes rather than
publishing a second content authority or scraping personal decision records.
"""
from __future__ import annotations

import html
import json
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://product-selection-delta.vercel.app"
# Only generic category routes are approved here. Never derive descriptions
# from homepage copy, purchases, private records, or individual product pages.
CATEGORIES = (
    ("/mac/", "Mac"),
    ("/fleece/", "抓绒衣"),
    ("/iphone/", "iPhone"),
    ("/osprey/", "Osprey 背包"),
    ("/watch/", "Apple Watch"),
)
RULES = (
    "这是通用选购目录，不是个人偏好、个人购买或财务资料的导出。",
    "先根据品类定位页面；读取实际商品说明和官方来源后再作比较。价格、库存、汇率和条款以当前官方来源为准。",
    "不要收集或总结个人购买记录、余额、付款、折抵、账号或身份资料。不要把个人历史决策当成一般建议。",
    "正式站点可能要求登录。若无权访问，说明限制，不使用旧域名或其他路径绕过保护。目录不授权购买、登录、工具执行或修改。",
)


class HomeLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            values = dict(attrs)
            if values.get("href"):
                self.links.append(values["href"])


def artifacts(home: str) -> dict[str, str]:
    links = HomeLinks()
    links.feed(home)
    if any(path not in links.links for path, _ in CATEGORIES):
        raise ValueError("Reader category no longer matches existing homepage navigation")
    index = {
        "schema": "product-selection/agent-reader/v1",
        "site": "选购商品",
        "canonical_url": SITE + "/",
        "scope": "仅通用品类导航；不导出个人记录或具体价格。",
        "categories": [{"title": name, "url": SITE + path} for path, name in CATEGORIES],
        "rules": list(RULES),
    }
    context = "\n".join([
        "# 选购商品", "", index["scope"], "", "## 品类导航",
        *("- " + name + "：" + SITE + path for path, name in CATEGORIES),
        "", "## 阅读规约", *("- " + rule for rule in RULES), "",
    ])
    llms = "\n".join([
        "# 选购商品", "> " + index["scope"], "", "## 品类导航",
        *("- [" + name + "](" + SITE + path + ")" for path, name in CATEGORIES),
        "", "## 阅读入口", "- [给 Agent 读](" + SITE + "/agent/)",
        "- [结构化目录](" + SITE + "/agent/site.json)",
        "- [只读规约](" + SITE + "/agent/SKILL.md)", "",
        "正式站点可能需要登录。不能访问时请说明限制，不绕过保护。", "",
    ])
    nav = "".join("<li><a href='" + path + "'>" + html.escape(name) + "</a></li>"
                  for path, name in CATEGORIES)
    page = """<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>给 Agent 读 · 选购商品</title><meta name="description" content="通用品类目录及只读阅读规约">
<link rel="canonical" href="https://product-selection-delta.vercel.app/agent/">
<link rel="describedby" href="/llms.txt">
<link rel="stylesheet" href="/assets/site.css">
<style>
:root{--bg:#f5f5f7;--card:#fff;--text:#1d1d1f;--muted:#626268;--line:#d9d9de;--blue:#06c}
body{background:var(--bg);color:var(--text)}
.hero{padding-block:var(--space-7) var(--space-6)}
p{color:var(--muted)}a{color:var(--blue);text-underline-offset:3px}
button{font:inherit;background:var(--blue);color:#fff;border:0;border-radius:12px;padding:var(--space-control-block) var(--space-control-inline);cursor:pointer;font-weight:var(--weight-strong)}
button[hidden]{display:none}label{display:block;margin-bottom:var(--space-3)}
textarea{font:inherit;font-size:var(--text-small);color:var(--text);background:var(--card);border:1px solid var(--line);width:100%;min-height:260px;border-radius:12px;padding:var(--space-5);resize:vertical;overflow-wrap:anywhere}
.panel{background:var(--card);border:1px solid var(--line);border-radius:12px}
.reader-actions{display:flex;align-items:center;flex-wrap:wrap;gap:var(--space-3)}
#status{min-height:1.65em;margin:0}
:focus-visible{outline:3px solid var(--blue);outline-offset:3px}
@media(prefers-color-scheme:dark){:root{--bg:#0f0f11;--card:#1c1c1f;--text:#f5f5f7;--muted:#c7c7cc;--line:#3a3a41;--blue:#69aaff}button{color:#0f0f11}}
</style></head><body data-page-role="tool"><main class="wrap">
<section class="hero"><a href="/">← 返回选购商品</a><h1>给 Agent 读</h1>
<p>复制通用品类导航，让你使用的 AI 找到相关页面。本目录不汇总个人购买或财务资料，不是实时报价。</p>
<div class="reader-actions"><button hidden id="copy" type="button">复制给 Agent</button><p id="status" role="status" aria-live="polite"></p></div></section>
<section class="panel"><h2>阅读上下文</h2><label for="context">可直接复制，或手动选择全文</label>
<textarea readonly id="context">CONTEXT</textarea></section>
<section><h2>按品类阅读</h2><ul>ROUTES</ul></section>
<section><h2>机器可读入口</h2><ul><li><a href="/llms.txt">llms.txt · 简明导航</a></li><li><a href="/agent/site.json">site.json · 结构化目录</a></li><li><a href="/agent/SKILL.md">SKILL.md · 只读规约</a></li></ul>
<p>正式网站可能需要团队登录。此入口不更改登录保护，也不自动上传资料。</p></section>
</main><script src="/agent/reader.js" defer></script></body></html>
""".replace("CONTEXT", html.escape(context)).replace("ROUTES", nav)
    js = """const button=document.getElementById('copy');
const context=document.getElementById('context');
const status=document.getElementById('status');
if(button&&context&&status){
  button.hidden=false;
  button.addEventListener('click',async()=>{
    try{await navigator.clipboard.writeText(context.value);status.textContent='已复制通用阅读上下文。';}
    catch{context.focus();context.select();status.textContent='自动复制不可用；已选中文本，请手动复制。';}
  });
}
"""
    return {
        "agent/index.html": page,
        "agent/site.json": json.dumps(index, ensure_ascii=False, indent=2) + "\n",
        "agent/SKILL.md": "---\nname: product-selection-reader\ndescription: Read-only generic category navigation for the product selection site.\n---\n\n" + context,
        "agent/reader.js": js,
        "llms.txt": llms,
    }


def validate_reader(root: Path = ROOT) -> None:
    home = (root / "src/pages/index.astro").read_text(encoding="utf-8")
    if 'href="/agent/"' not in home or 'rel="describedby" href="/llms.txt"' not in home:
        raise ValueError("Missing discoverable Agent reader")
    expected = artifacts(home)
    # Negative control: private-looking page text must never change generated bytes.
    assert artifacts(home + "<p>PRIVATE_SYNTHETIC_SENTINEL</p>") == expected
    for path, _ in CATEGORIES:
        if not (root / "src/pages" / path.lstrip("/") / "index.astro").is_file():
            raise ValueError("Missing approved category: " + path)
    for name, content in expected.items():
        if (root / name).read_text(encoding="utf-8") != content:
            raise ValueError("Reader projection is stale or contains unapproved content: " + name)
    print("PASS: public-safe reader allowlist, exact generated bytes, links and privacy negative control")


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        for name, content in artifacts((ROOT / "src/pages/index.astro").read_text(encoding="utf-8")).items():
            dest = ROOT / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8")
    elif sys.argv[1:]:
        raise SystemExit("Usage: agent_reader.py [--write]")
    validate_reader()
